out = widgets.Output(layout={'border':'1px solid #ccc','padding':'8px',
                              'height':'320px','overflow':'auto'})

def log(msg, clear=False):
    with out:
        if clear: clear_output()
        print(msg)

# ---- Tab 1: Data ----
fit_path = widgets.Text(description="fitness csv", layout=widgets.Layout(width='90%'))
stab_path= widgets.Text(description="ddg csv",     layout=widgets.Layout(width='90%'))
dbl_path = widgets.Text(description="doubles csv", layout=widgets.Layout(width='90%'))
stab_sign= widgets.Checkbox(value=False, description="stability table already has higher = more stable")
btn_load = widgets.Button(description="Load + validate data", button_style='info')
def on_load(_):
    log("loading tables ...", clear=True)
    try:
        STATE["singles"]=load_table(fit_path.value)
        STATE["stab"]=load_table(stab_path.value)
        STATE["doubles"]=load_table(dbl_path.value)
        for nm,df in [("fitness",STATE["singles"]),("ddg",STATE["stab"]),("doubles",STATE["doubles"])]:
            if df is not None: log(f"{nm}: columns = {list(df.columns)}")
        log("--- validation ---")
        log(validate_table(STATE["singles"],"fitness"))
        log(validate_table(STATE["stab"],"stability"))
        log("If a table shows MISMATCH, fix SEQ_OFFSET in Cell 2 and reload. "
            "If columns are wrong, rename to pos,wt,mut,fitness / ddg.")
    except Exception as e:
        log(f"ERROR: {e}")
btn_load.on_click(on_load)
tab_data = widgets.VBox([
    widgets.HTML("<b>Upload CSVs via the file panel (left), paste their paths, then load.</b>"),
    fit_path, stab_path, dbl_path, stab_sign, btn_load])

# ---- Tab 2: Models ----
btn_models = widgets.Button(description="Load 6 ESM models", button_style='warning')
def on_models(_):
    log("loading models (slow on first run; cached to Drive after) ...", clear=True)
    try: log(load_models(progress=lambda s: log(s)))
    except Exception as e: log(f"ERROR: {e}")
btn_models.on_click(on_models)
tab_models = widgets.VBox([
    widgets.HTML("<b>Loads ESM-1b + ESM-1v ×5. First run downloads ~15 GB to Drive.</b>"),
    btn_models])

# ---- Tab 3: Score + recommend ----
target_size = widgets.IntSlider(value=12, min=5, max=30, description="target set")
btn_score = widgets.Button(description="Run consensus scorer", button_style='success')
def on_score(_):
    if STATE["loaded"] is None: log("Load models first (Models tab).", clear=True); return
    log("scoring ...", clear=True)
    try:
        dist=score_all(progress=lambda s: log(s))
        log("consensus vote distribution:\n"+dist)
        k,n=build_candidates(target_size.value)
        log(f"recommended set: consensus>={k}, {n} variants")
    except Exception as e: log(f"ERROR: {e}")
btn_score.on_click(on_score)
tab_score = widgets.VBox([target_size, btn_score])

# ---- Tab 4: Labels ----
btn_label = widgets.Button(description="Attach fitness + stability", button_style='success')
def on_label(_):
    if STATE["cand"] is None: log("Run the scorer first (Score tab).", clear=True); return
    try:
        cf,cs,nd=attach_labels(stab_sign.value)
        log(f"label coverage — fitness {cf:.0%}, stability {cs:.0%}", clear=True)
        log(f"fully-labeled recommended variants: {nd}")
        if nd==0: log("No dual-labeled variants — check coverage / column names.")
    except Exception as e: log(f"ERROR: {e}")
btn_label.on_click(on_label)
tab_label = widgets.VBox([
    widgets.HTML("<b>Joins the recommended set to the public tables.</b>"), btn_label])

# ---- Tab 5: Results ----
plot_out = widgets.Output()
btn_pareto = widgets.Button(description="Pareto front", button_style='primary')
btn_enrich = widgets.Button(description="Enrichment + correlation", button_style='primary')
def on_pareto(_):
    d=STATE["d"]
    if d is None or not len(d): log("Attach labels first (Labels tab).", clear=True); return
    d=d.copy(); d["front"]=pareto_mask(d)
    with plot_out:
        clear_output()
        plt.figure(figsize=(5,4))
        plt.scatter(d["fitness"], d["stability"], c=d["consensus"], cmap="viridis", s=60)
        fr=d[d["front"]].sort_values("fitness")
        plt.plot(fr["fitness"], fr["stability"], 'r--o', alpha=.6, label="Pareto front")
        plt.colorbar(label="consensus votes")
        plt.xlabel("fitness"); plt.ylabel("stability (higher=more stable)")
        plt.legend(); plt.title("Recommended variants"); plt.tight_layout(); plt.show()
    log(f"Pareto-optimal variants: {int(d['front'].sum())}", clear=True)
def on_enrich(_):
    if STATE["all_singles"] is None: log("Attach labels first.", clear=True); return
    r=enrichment()
    if r is None: log("Need both labels loaded.", clear=True); return
    log(f"background dual-improved: {r['K']}/{r['N']} = {r['bg_frac']:.1%}", clear=True)
    log(f"recommended dual-improved: {r['x']}/{r['n']} = {r['rec_frac']:.1%}")
    log(f"hypergeometric p = {r['p']:.3g}")
    log(f"Spearman(votes, joint desirability) = {r['rho']:.3f} (p={r['pv']:.3g})")
btn_pareto.on_click(on_pareto); btn_enrich.on_click(on_enrich)
tab_results = widgets.VBox([widgets.HBox([btn_pareto, btn_enrich]), plot_out])

tabs = widgets.Tab(children=[tab_data,tab_models,tab_score,tab_label,tab_results])
for i,t in enumerate(["1. Data","2. Models","3. Score","4. Labels","5. Results"]):
    tabs.set_title(i,t)

display(widgets.HTML("<h3>GB1 co-optimization control panel</h3>"))
display(tabs)
display(widgets.HTML("<b>Status / output:</b>"))
display(out)